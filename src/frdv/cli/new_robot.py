"""frdv-new-robot: create a robot config from an MJCF or URDF file.

    frdv-new-robot path/to/robot.xml --name myrobot            # writes ./frdv_conf/robot/myrobot.yaml
    frdv-retarget robot=myrobot dataset=lafan1 data=...         # picked up automatically from ./frdv_conf

Finds the legs and arms from the kinematic tree and geometry (not from names): hip / knee /
ankle / shoulder / elbow / wrist joints, toe and sole points from the foot geometry, pelvis at the
hip-joint midpoint, orientation markers on the hand and limb-roll links, the standing height and a
nominal keyframe. Left/right come from link names when they are unambiguous, else from the feet.
URDF files work directly (a floating base is added, fixed links are kept, meshes are resolved).
"""

from __future__ import annotations

import argparse
import os
import re

import mujoco

from .common import model_height, nominal_qpos, resolve_path

# canonical keypoint -> name fragments, most specific first
PARTS = {
    "hip": ["hip_pitch", "hip_roll", "hip_yaw", "hip", "thigh", "upleg", "upper_leg", "femur"],
    "knee": ["knee", "shin", "calf", "shank", "lower_leg", "tibia"],
    "ankle": ["ankle_pitch", "ankle_roll", "ankle", "foot"],
    "toe": ["toe", "foot_tip", "sole", "foot"],
    "shoulder": ["shoulder_pitch", "shoulder_roll", "shoulder", "upper_arm", "arm_link1", "humerus"],
    "elbow": ["elbow", "forearm", "lower_arm", "arm_link4"],
    "wrist": ["rubber_hand", "hand", "wrist_yaw", "wrist", "palm", "arm_link7"],
}
CENTER = {"pelvis": ["pelvis", "base_link", "base", "hips", "root", "trunk"],
          "spine": ["waist_yaw", "waist", "torso", "spine", "chest", "abdomen"]}
SIDE = {"left": [r"(^|[_\W])l(eft)?([_\W]|$)", r"^left", r"left", r"^l_", r"_l$", r"^l(?=[A-Z])"],
        "right": [r"(^|[_\W])r(ight)?([_\W]|$)", r"^right", r"right", r"^r_", r"_r$", r"^r(?=[A-Z])"]}


def _names(m, obj, n):
    return [mujoco.mj_id2name(m, obj, i) or "" for i in range(n)]


def _side_ok(name, side):
    return any(re.search(p, name, flags=re.I if p.islower() else 0) for p in SIDE[side])


def guess_keypoints(m):
    bodies = _names(m, mujoco.mjtObj.mjOBJ_BODY, m.nbody)[1:]
    sites = _names(m, mujoco.mjtObj.mjOBJ_SITE, m.nsite)
    out, used = {}, set()
    root_body = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_BODY, int(m.jnt_bodyid[0])) or bodies[0]
    def has(name, frag):  # case- and underscore-insensitive fragment match
        n = name.lower()
        return frag in n or frag.replace("_", "") in n.replace("_", "")

    for kp, frags in CENTER.items():
        cands = [b for f in frags for b in bodies if has(b, f) and b not in used]
        pick = cands[0] if cands else (root_body if kp == "pelvis" else None)
        if pick:
            out[kp] = pick
            used.add(pick)
    for side in ("left", "right"):
        for part, frags in PARTS.items():
            pick = None
            for f in frags:
                for b in bodies + sites:
                    if b and has(b, f) and _side_ok(b, side) and b not in used:
                        pick = b
                        break
                if pick:
                    break
            if pick:
                out[f"{side}_{part}"] = pick
                used.add(pick)
    return out


def guess_feet(m):
    sites = _names(m, mujoco.mjtObj.mjOBJ_SITE, m.nsite)
    return [s for s in sites if re.search(r"heel|sole|contact|(foot|toe)[_\W]?(f|h|b|l|r|in|out|pt|point|corner|\d)", s, re.I)
            and not s.lower().startswith("mocap")]


MARKER_WEIGHTS = {"thumb": 1000, "middle": 1000, "pinky": 1000, "upper_arm_up": 250, "upper_arm_down": 250,
                  "forearm_up": 1000, "forearm_down": 1000}


def _vec(v):
    return "[" + ", ".join(f"{x:.4f}" for x in v) + "]"


def build_config(src: str, name: str, markers: bool = True):
    """(yaml text, report lines) for a robot file (MJCF or URDF)."""
    import numpy as np
    from ..automap import analyze
    from ..robot_model import load_model

    m = load_model(src)
    lay = analyze(m)
    guess = guess_keypoints(m)
    key = lay.nominal_key
    height = lay.height or model_height(m, nominal_qpos(m, key))
    order = ["pelvis", "spine"] + [f"{s}_{p}" for s in ("left", "right") for p in PARTS]
    lines = [
        f"# Generated by frdv-new-robot from {src}",
        "# Keypoints found from the kinematic tree (limb chains, joint clusters, foot geometry).",
        "# Check with:  frdv-check robot=<name> ...   and edit any link / offset that looks wrong.",
        f"name: {name}",
        f"xml: {src}",
        f"height: {height:.3f}            # standing height at the nominal pose (m)",
        f"nominal_key: {key if key else 'null'}" + ("" if key else "      # no keyframe: qpos0 is used"),
        "target_offset: [0.0, 0.0, 0.0]",
        "keypoints:                # canonical name: {link, weight, offset (link frame, optional)}",
    ]
    report, missing = [], []
    for k in order:
        if k in lay.keypoints:
            b, off = lay.keypoints[k]
            w = 500 if k.endswith("wrist") else 1000
            extra = f", offset: {_vec(off)}" if np.linalg.norm(off) > 1e-4 else ""
            lines.append(f"  {k + ':':22s} {{link: {b}, weight: {w}{extra}}}")
            report.append(f"    {k:22s} -> {b}" + (f"  + {_vec(off)}" if extra else ""))
        elif k in guess:
            lines.append(f"  {k + ':':22s} {{link: {guess[k]}, weight: 1000}}   # from the link name only")
            report.append(f"    {k:22s} -> {guess[k]}  (name match)")
        else:
            missing.append(k)
            lines.append(f"  # {k}: {{link: ???, weight: 1000}}")
    if markers and lay.markers:
        lines.append("  # optional orientation markers: used only with dataset.augmentation=true")
        for k, b in lay.markers.items():
            w = MARKER_WEIGHTS.get(k.split("_", 1)[1], 1000)
            lines.append(f"  {k + ':':22s} {{link: {b}, weight: {w}, calibrate: true}}")
    feet = [f"  - {{link: {b}, offset: {_vec(o)}}}" for b, o in lay.foot_points] or \
           [f"  - {f}" for f in guess_feet(m)]
    lines += ["foot_points:" + ("" if feet else " []   # none found: collision capsules still keep the robot above ground")]
    lines += feet
    lines += ["ground_points: auto           # extreme surface points of every link stay above the floor",
              "capsule_ground: true", "joint_reg_weight: 1.0", "joint_reg_weights: {}",
              "self_collision: {pairs: [], margin: 0.05}", ""]
    head = [f"  height {height:.2f} m, nominal key: {key}, {len(feet)} foot point(s), "
            f"{len(lay.markers) if markers else 0} orientation marker(s)", "  keypoints:"]
    tail = [f"  not found: {', '.join(missing)}"] if missing else []
    tail += [f"  note: {n}" for n in lay.notes]
    return "\n".join(lines), head + report + tail


def main(argv=None):
    import sys
    argv = list(sys.argv[1:] if argv is None else argv)
    # accept hydra-style key=value too:  frdv-new-robot xml=robot.urdf name=foo
    conv = []
    for a in argv:
        k, eq, v = a.partition("=")
        if eq and not a.startswith("-") and k in ("xml", "name", "out"):
            conv += ([v] if k == "xml" else [f"--{k}", v])
        else:
            conv.append(a)
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("xml", help="robot MJCF or URDF (a floating base is added if missing)")
    ap.add_argument("--name", default=None, help="config name (default: file stem)")
    ap.add_argument("--out", default=os.environ.get("FRDV_CONFIG_DIR", "frdv_conf"), help="config folder")
    ap.add_argument("--no-markers", action="store_true", help="track positions only (no orientation markers)")
    ap.add_argument("--force", action="store_true", help="overwrite an existing config")
    args = ap.parse_args(conv)

    src = resolve_path(args.xml)
    if not os.path.exists(src):
        raise SystemExit(f"not found: {src}")
    name = args.name or os.path.splitext(os.path.basename(src))[0]
    path = os.path.join(args.out, "robot", f"{name}.yaml")
    if os.path.exists(path) and not args.force:
        raise SystemExit(f"{path} exists (use --force to overwrite)")
    text, report = build_config(src, name, markers=not args.no_markers)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote {path}")
    print("\n".join(report))
    print(f"\nnext:  frdv-check robot={name} dataset=lafan1 data=<one clip>   then   frdv-retarget robot={name} ...")


if __name__ == "__main__":
    main()
